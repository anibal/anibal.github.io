/**
 * Generates src/styles/font-overrides.css — metric-matched fallback faces
 * (size-adjust / ascent-override / descent-override / line-gap-override) so
 * `font-display: swap` causes no layout shift and no LCP repaint (handoff:
 * CLS = 0 gate). Metrics come from the @capsizecss metrics collection via
 * fontaine. Re-run if fonts change: `node scripts/build-font-overrides.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { generateFontFace, getMetricsForFamily } from 'fontaine';

const faces = [
  { family: 'Fraunces', fallback: 'Georgia', italicLocal: 'Georgia Italic' },
  { family: 'IBM Plex Sans', fallback: 'Arial', italicLocal: 'Arial Italic' },
  { family: 'IBM Plex Mono', fallback: 'Courier New', italicLocal: null }, // mono italic unused
];

const out = [
  `/* ------------------------------------------------------------------`,
  `   GENERATED by scripts/build-font-overrides.mjs — do not hand-edit.`,
  `   Metric-matched local fallbacks: swap renders into an identical box.`,
  `   ------------------------------------------------------------------ */`,
  ``,
];

for (const { family, fallback, italicLocal } of faces) {
  const metrics = await getMetricsForFamily(family);
  const fallbackMetrics = await getMetricsForFamily(fallback);
  if (!metrics || !fallbackMetrics) {
    throw new Error(`Missing metrics for ${family} or ${fallback}`);
  }
  const name = `${family} Fallback`;
  const face = generateFontFace(metrics, { name, font: fallback, metrics: fallbackMetrics });
  out.push(face);

  if (italicLocal) {
    // Same vertical metrics for the italic cut; swap in the matching local italic.
    const italic = face
      .replace(`local("${fallback}")`, `local("${italicLocal}")`)
      .replace('}', '  font-style: italic;\n}');
    out.push(italic);
  }
}

writeFileSync('src/styles/font-overrides.css', out.join('\n\n') + '\n');
console.log(readFileSync('src/styles/font-overrides.css', 'utf8'));
